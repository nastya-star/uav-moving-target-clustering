function stg_paragraphs (cfg, env, Y, Dc, Md, Mx, H, Cm, V)
  % STG_PARAGRAPHS  Короткі абзаци з підтвердженими результатами (LaTeX).
  %
  % Усі числа підставляються з результатів поточного запуску. Твердження,
  % які залежать від результату перевірки, друкуються лише тоді, коли
  % відповідну умову виконано; інакше запуск зупиняється з помилкою.

  global STG_RUNS
  R39 = Y(1).R; R44 = Y(2).R; E39 = Y(1).E; E44 = Y(2).E;
  n39 = columns (Y(1).D.A); n44 = columns (Y(2).D.A);
  nruns = numel (STG_RUNS);
  assert (all ([STG_RUNS.errnum] == 0 & [STG_RUNS.status] == 5));
  assert (R39.ok && R44.ok && E39.unique && E44.unique && E39.dual_unique && E44.dual_unique);
  assert (Y(1).Uq.all_optimal && Y(2).Uq.all_optimal);
  assert (all (Y(1).Sn.basis_kept) && all (Y(2).Sn.basis_kept));
  assert (Y(1).Sn.all_basis_kept && Y(2).Sn.all_basis_kept);
  assert (isequal (R39.active, [1 3 5 7 9]) && isequal (R44.active, [1 3 5 7 9]));
  assert (Mx.all_days_unique);
  assert (isequal (Mx.iron.cmp', [1 1 -1]) && isequal (Mx.protein.cmp', [1 1 -1]));

  fid = fopen (fullfile (cfg.texdir, 'paragraphs_uk.tex'), 'w');
  P = @(varargin) fprintf (fid, varargin{:});
  P ('%% Згенеровано run_all.m. Абзаци з результатами перевірки в GNU Octave через GLPK.\n');
  P ('%% Початковий текст роботи не змінено; ці абзаци подано окремо.\n\n');

  % ---------------------------------------------------------------------------
  P ('\\paragraph{Середовище та параметри розв’язувача.}\n');
  P (['Обчислення виконано в GNU Octave %s функцією \\texttt{glpk}, яка викликає бібліотеку GLPK %s ', ...
      '(%s). '], env.octave, env.glpk_version, env.os);
  g = cfg.glpk;
  P (['Усі задачі розв’язано двофазним прямим симплекс-методом без пресолвера ', ...
      '(\\texttt{lpsolver}=%d, \\texttt{dual}=%d, \\texttt{presol}=%d). '], g.lpsolver, g.dual, g.presol);
  P (['Використано рівноважне масштабування (\\texttt{scale}=%d), вибір змінної за найкрутішим ', ...
      'ребром (\\texttt{price}=%d) і тест відношень Гарріса (\\texttt{rtest}=%d). '], g.scale, g.price, g.rtest);
  P (['Допуски розв’язувача: \\texttt{tolbnd}$=%s$, \\texttt{toldj}$=%s$, \\texttt{tolpiv}$=%s$. '], ...
     p10 (g.tolbnd), p10 (g.toldj), p10 (g.tolpiv));
  P (['Запуск вважали успішним лише за коду завершення~0 і статусу~5 (оптимальний розв’язок). ', ...
      'Цю умову виконано в усіх %d запусках. '], nruns);
  P (['Носій визначали умовою $x_i^*>%s$, активні рядки --- умовою $|s_j|\\le%s\\max\\{1,|b_j|\\}$.\n\n'], ...
     p10 (cfg.tol_support), p10 (cfg.tol_active));

  % ---------------------------------------------------------------------------
  P ('\\paragraph{Вихідні дані.}\n');
  sha = hash ('sha256', fileread (fullfile (cfg.datadir, 'stigler.mod')));
  assert (strcmp (sha, cfg.sha256_stigler_mod), 'stigler.mod відрізняється від оригіналу GLPK 4.65');
  P (['Матрицю 1939 року взято з файлу \\texttt{stigler.mod} архіву GLPK~4.65 без змін: контрольна сума ', ...
      'SHA-256 файлу (\\texttt{%s\\ldots}) збігається із сумою оригіналу. ', ...
      'Файл містить %d продуктів і дев’ять показників у порядку: енергія, білок, кальцій, залізо, ', ...
      'вітамін~A, тіамін, рибофлавін, ніацин, вітамін~C. '], sha(1:16), n39);
  P (['Коефіцієнти задано на один долар витрат, ціни --- в центах за торгову одиницю. ']);
  nw = sum (! isnan (Dc.edible)); bad = find (! isnan (Dc.edible) & Dc.edible > Dc.edible_cap)';
  P (['Для %d продуктів із ваговою торговою одиницею перевірено стовпець їстівної маси на один долар: ', ...
      'у %d випадках він узгоджується з ціною та масою торгової одиниці. '], nw, nw - numel (bad));
  D39 = Y(1).D;
  for i = bad
    P (['Для продукту \\texttt{%s} файл містить %d~г, тоді як торгова одиниця %s за %s~цента дає ', ...
        '%s~г; цей стовпець до моделі не входить. '], D39.key{i}, D39.weight(i), ...
       strrep (D39.unit{i}, 'oz.', 'унції'), tx (D39.price(i), 1), ...
       tx (D39.lb_per_unit(i) * cfg.lb_gram / (D39.price(i) / 100), 1));
  end
  P ('\n\n');

  D44 = Y(2).D;
  P (['Матрицю 1944 року утворюють %d рядків таблиці~B на с.~307 статті Стіглера. ', ...
      'Таблиця~B не містить стовпця торгових одиниць: для продуктів №~1--74 одиниці взято з таблиці~A, ', ...
      'для №~78--80 --- з приміток до таблиці~B. Порожні клітинки передано нулями. '], n44);
  sc = fullfile (cfg.root, 'source_check', 'tableB_p307_comparison.csv');
  if (exist (sc, 'file'))
    L = strsplit (strtrim (fileread (sc)), "\n");
    ncell = numel (L) - 1; nmatch = 0;
    for k = 2:numel (L)
      t = strsplit (strtrim (L{k}), ',', 'CollapseDelimiters', false);
      nmatch += strcmp (t{6}, '1');
    end
    P (['Звірка файлу \\texttt{stigler1944.csv} зі сканом сторінки підтвердила %d зі %d клітинок ', ...
        '(ціна та дев’ять показників у кожному рядку). '], nmatch, ncell);
  else
    P ('Звірку файлу \\texttt{stigler1944.csv} зі сканом сторінки в цьому запуску не виконано. ');
  end
  dv = abs (Dc.dev_units); [jj, ii] = find (dv > 1);
  dv2 = dv; dv2(dv > 1) = NaN;
  P (['Для %d продуктів, які є в таблиці~A, перевірено співвідношення ', ...
      '$a^{1944}_{ji}=a^{1939}_{ji}p^{1939}_i/p^{1944}_i$. '], Dc.n_cross);
  if (numel (jj) == 1)
    P (['Відхилення не перевищує %s одиниці останнього друкованого знака в усіх клітинках, крім однієї. ', ...
        'Виняток --- білок продукту №~%d: у файлі %d~г, за таблицею~A --- %s~г; ', ...
        'остання цифра на скані читається неоднозначно (3 або 8). '], tx (max (dv2(:)), 2), ...
       D44.id(ii), D44.A(jj, ii), tx (Dc.pred(jj, ii), 2));
    % числове порівняння двох запусків і точний сертифікат для варіанта з 393
    assert (abs (V.R.C - R44.C) <= 1e-13 && max (abs (V.R.x - R44.x)) <= 1e-13 ...
            && max (abs (V.R.u - R44.u)) <= 1e-13 && max (abs (V.R.r - R44.r)) <= 1e-13);
    assert (V.E.unique && isequal (V.R.support, R44.support) ...
            && max (abs (V.Rd.m(V.Rd.inactive) - Y(2).Rd.m(V.Rd.inactive))) <= 1e-9);
    P (['Заміна %d на 393 не змінює $C^*$, $x^*$, $u^*$, зведені вартості та значення $m_j$: ', ...
        'цей продукт не входить до носія, а множник білкового рядка дорівнює нулю. '], D44.A(jj, ii));
  else
    P ('Найбільше відхилення дорівнює %s одиниці останнього друкованого знака. ', tx (max (dv(:)), 2));
  end
  P (['Для продуктів №~%d і №~%d їстівна маса на один долар із приміток (%d і %d~г) узгоджується з ', ...
      'ціною та торговою одиницею (%s і %s~г).\n\n'], Dc.footnote(1, 1), Dc.footnote(2, 1), ...
     Dc.footnote(1, 2), Dc.footnote(2, 2), tx (Dc.footnote(1, 3), 1), tx (Dc.footnote(2, 3), 1));

  % ---------------------------------------------------------------------------
  P ('\\paragraph{Пряма і двоїста задачі.}\n');
  P (['Для кожної матриці окремо розв’язано пряму задачу ', ...
      '$\\min\\{\\mathbf1^\\top x:\\ Ax\\ge b,\\ x\\ge0\\}$ і двоїсту задачу ', ...
      '$\\max\\{b^\\top u:\\ A^\\top u\\le\\mathbf1,\\ u\\ge0\\}$. ']);
  P (['Функція \\texttt{glpk} повертає множники рядків як похідні оптимального значення за правими ', ...
      'частинами. Тому для прямої задачі з рядками «$\\ge$» множники збігаються з $u^*\\ge0$, а для ', ...
      'двоїстої задачі з рядками «$\\le$» --- з $x^*\\ge0$; зміна знака не потрібна. ']);
  P (['Множники прямої задачі відрізняються від розв’язку двоїстої не більше ніж на $%s$ (1939) і ', ...
      '$%s$ (1944).\n\n'], sci (R39.checks.u_vs_dual_lp), sci (R44.checks.u_vs_dual_lp));
  P (['Одержано $C^*_{1939}=%s$ і $C^*_{1944}=%s$ дол./день. '], tx (R39.C, 15), tx (R44.C, 15));
  P (['За 365 днів це %s і %s дол., за $365{,}25$ дня --- %s і %s дол. '], tx (365 * R39.C, 6), ...
     tx (365 * R44.C, 6), tx (365.25 * R39.C, 6), tx (365.25 * R44.C, 6));
  P (['У табл.~\\ref{tab:glpk-solution-1939} і \\ref{tab:glpk-solution-1944} наведено оптимальні вектори ', ...
      '$x^*$, у табл.~\\ref{tab:glpk-dual-1939} і \\ref{tab:glpk-dual-1944} --- надходження $Ax^*$, запаси ', ...
      '$s=Ax^*-b$ і множники $u^*$. Повні вектори з %d і %d компонент та зведені вартості ', ...
      '$r=\\mathbf1-A^\\top u^*$ збережено у файлах CSV. '], n39, n44);
  c1 = R39.checks; c2 = R44.checks;
  mxv = max ([c1.primal_infeas, c1.dual_infeas, c2.primal_infeas, c2.dual_infeas]);
  mxg = max ([c1.gap, c2.gap, c1.gap_two_lps, c2.gap_two_lps]);
  mxc = max ([c1.comp_rows, c1.comp_cols, c2.comp_rows, c2.comp_cols]);
  P (['Порушення умов $Ax^*\\ge b$, $x^*\\ge0$, $A^\\top u^*\\le\\mathbf1$, $u^*\\ge0$ не перевищує $%s$, ', ...
      'двоїстий розрив --- $%s$, добутки $|u_j^*s_j|$ і $|x_i^*r_i|$ --- $%s$ ', ...
      '(табл.~\\ref{tab:glpk-checks}). '], sci (mxv), sci (mxg), sci (mxc));
  P (['В обох задачах додатними є п’ять компонент $x^*$ і п’ять компонент $u^*$. Активні рядки: енергія, ', ...
      'кальцій, вітамін~A, вітамін~B$_2$, вітамін~C.\n\n']);

  % ---------------------------------------------------------------------------
  P ('\\paragraph{Фізичні кількості.}\n');
  Q44 = Y(2).Q; Q39 = Y(1).Q;
  iF = find (D44.id == 1); iP = find (D44.id == 78);
  P (['Кількість торгових одиниць обчислено за формулою $z_i=100x_i^*/p_i$, де $p_i$ --- ціна торгової ', ...
      'одиниці в центах. У табл.~\\ref{tab:glpk-units-1939} і \\ref{tab:glpk-units-1944} наведено добові ', ...
      'кількості та річні кількості за 365 і $365{,}25$ дня. ']);
  P (['Торгова одиниця пшеничного борошна дорівнює 10 фунтам, борошна для млинців --- 20 унціям, тобто ', ...
      '$1{,}25$ фунта. За $365{,}25$ дня розв’язок 1944 року містить %s фунта пшеничного борошна і %s фунта ', ...
      'борошна для млинців, за 365 днів --- %s і %s фунта.\n\n'], tx (Q44.lb_36525(iF), 3), ...
     tx (Q44.lb_36525(iP), 3), tx (Q44.lb_365(iF), 3), tx (Q44.lb_365(iP), 3));

  % ---------------------------------------------------------------------------
  h = H.y1944;
  assert (isequal (sort (h.idx(:))', R44.support));
  short = find (h.ratio_cost(:, 1) < 1)';
  assert (! isempty (short) && h.theta(1) < 1);
  assert (365 * h.C_up <= h.total && h.total <= 365 * h.C_dn);
  P ('\\paragraph{Історичний підсумок 1944 року.}\n');
  P (['Сума вартостей у стовпці 1944 року таблиці~2 дорівнює %s дол. Мінімум для опублікованої матриці ', ...
      'становить %s дол. за 365 днів і %s дол. за $365{,}25$ дня. '], tx (h.sum_cost, 2), ...
     tx (365 * R44.C, 4), tx (365.25 * R44.C, 4));
  P (['Стаття Стіглера не називає кількість днів у році; сума $24{,}50$ дол. на с.~311 відповідає ', ...
      '365 дням ($365\\cdot3/44{,}7=%s$). Тому історичний підсумок зіставлено зі значенням за 365 днів: ', ...
      'різниця дорівнює %s дол., або %s\\%%. '], tx (365 * 3 / 44.7, 2), tx (365 * R44.C - h.total, 4), ...
     tx (100 * (365 * R44.C - h.total) / h.total, 3));
  P (['Історичний раціон містить ті самі п’ять продуктів, що й носій $x^*$ ', ...
      '(табл.~\\ref{tab:glpk-historic-1944}). ']);
  nmu = {'енергії', 'білка', 'кальцію', 'заліза', 'вітаміну~A', 'вітаміну~B$_1$', 'вітаміну~B$_2$', ...
         'ніацину', 'вітаміну~C'};
  s = cell (1, numel (short));
  for k = 1:numel (short)
    s{k} = sprintf ('%s\\%% вимоги для %s', tx (100 * h.ratio_cost(short(k), 1), 2), nmu{short(k)});
  end
  P (['Якщо його річні вартості поділити на 365, то за коефіцієнтами таблиці~B добове надходження ', ...
      'становить %s (табл.~\\ref{tab:glpk-historic-1944-nutrients}). '], strjoin (s, ', '));
  P (['Отже, історичний раціон не є допустимим для надрукованої матриці, і його вартість не суперечить ', ...
      'мінімуму %s дол. За властивістю $V(\\theta b)=\\theta V(b)$ бюджет %s дол. покриває щонайбільше ', ...
      '%s\\%% усіх вимог одночасно. '], tx (365 * R44.C, 4), tx (h.total, 2), tx (100 * h.theta(1), 3));
  P (['Коефіцієнти таблиці~B надруковано з кроком $0{,}1$ або 1. Якщо всі ненульові коефіцієнти збільшити ', ...
      'на половину кроку, мінімальна вартість за 365 днів дорівнює %s дол.; якщо зменшити --- %s дол. ', ...
      'Мінімум для кожної матриці, сумісної з округленням, лежить між цими значеннями, оскільки ', ...
      'поелементне збільшення $A$ не збільшує $V$. Історичний підсумок %s дол. належить цьому проміжку. ', ...
      'Перевірка не відновлює неокруглені дані Стіглера.\n\n'], tx (365 * h.C_up, 4), ...
     tx (365 * h.C_dn, 4), tx (h.total, 2));

  % ---------------------------------------------------------------------------
  P ('\\paragraph{Єдиність оптимального вектора.}\n');
  P (['На множині $\\{x:\\ Ax\\ge b,\\ x\\ge0,\\ \\mathbf1^\\top x=C^*\\}$ із повним обчисленим значенням ', ...
      '$C^*$ знайдено мінімум і максимум кожної координати: %d задачі для 1939 року і %d задач для ', ...
      '1944 року. Усі задачі завершено з кодом~0 і статусом~5. '], Y(1).Uq.n_lp, Y(2).Uq.n_lp);
  P (['Найбільша різниця між верхньою та нижньою межами координати дорівнює $%s$ і $%s$ дол./день ', ...
      '(табл.~\\ref{tab:glpk-uniqueness}). Це числовий результат, одержаний із допусками ', ...
      '\\texttt{tolbnd}$=$\\texttt{toldj}$=%s$; він не є доведенням єдиності.\n\n'], ...
     sci (Y(1).Uq.max_span), sci (Y(2).Uq.max_span), p10 (g.tolbnd));
  P (['Строгий висновок одержано точною перевіркою сертифіката. Усі коефіцієнти мають щонайбільше один ', ...
      'десятковий знак, тому $10A$ і $10b$ --- цілочислові. Для $S=\\{i:x_i^*>0\\}$ і ', ...
      '$J_+=\\{j:u_j^*>0\\}$ у цілочисловій арифметиці без округлень обчислено визначник і приєднану ', ...
      'матрицю для $10A_{J_+,S}$. ']);
  P (['Одержано $\\det(10A^{1939}_{J_+,S})=%s$ і $\\det(10A^{1944}_{J_+,S})=%s$, тобто ', ...
      '$\\det A^{1939}_{J_+,S}=-65357009378779/625$ і $\\det A^{1944}_{J_+,S}=267315835328303/5000$. '], ...
     bi_str (E39.det10), bi_str (E44.det10));
  P (['Точно перевірено такі умови: $x_S^*>0$; $u_{J_+}^*>0$; $Ax^*\\ge b$ з рівністю в рядках $J_+$; ', ...
      '$A^\\top u^*\\le\\mathbf1$ з рівністю в стовпцях $S$; $r_i>0$ для всіх $i\\notin S$; ', ...
      '$\\mathbf1^\\top x^*=b^\\top u^*$. ']);
  P (['Найменша зведена вартість поза носієм дорівнює %s для 1939 року і %s для 1944 року. '], ...
     tx (min (E39.r(setdiff (1:n39, R39.support))), 8), tx (min (E44.r(setdiff (1:n44, R44.support))), 8));
  P (['Отже, для обох табличних матриць оптимальний вектор $x^*$ єдиний. Запаси в рядках поза $J_+$ ', ...
      'строго додатні, тому двоїстий оптимум $u^*$ також єдиний. Висновок стосується зазначених ', ...
      'десяткових коефіцієнтів.\n\n']);

  % ---------------------------------------------------------------------------
  P ('\\paragraph{Чутливість до правих частин.}\n');
  md = max (abs ([Y(1).Sn.diff; Y(2).Sn.diff]));
  P (['Кожну з дев’яти вимог збільшено окремо на $1\\%%$ за незмінних інших. В усіх 18 випадках ', ...
      'фактичний приріст вартості збігається з $0{,}01\\,b_ju_j^*$; найбільша абсолютна різниця дорівнює ', ...
      '$%s$ дол. (табл.~\\ref{tab:glpk-sensitivity}). '], sci (md));
  P (['Точна перевірка показала, що в кожному з цих випадків базис $(S,J_+)$ залишається оптимальним. ', ...
      'Тому рівність $\\Delta C^*=0{,}01\\,b_ju_j^*$ для цих 18 збільшень є точною. Результат не поширюється ', ...
      'на довільні зміни правих частин. ']);
  P (['За одночасного збільшення всіх вимог на $1\\%%$ одержано %s і %s дол./день. Приріст дорівнює ', ...
      '$0{,}01\\,C^*$ з різницею не більше ніж $%s$ дол. і збігається із сумою дев’яти окремих приростів.\n\n'], ...
     tx (Y(1).Sn.all_cost, 12), tx (Y(2).Sn.all_cost, 12), ...
     sci (max (abs ([Y(1).Sn.all_delta - Y(1).Sn.all_pred, Y(2).Sn.all_delta - Y(2).Sn.all_pred]))));

  % ---------------------------------------------------------------------------
  P ('\\paragraph{Неактивність і надлишковість.}\n');
  in1 = Y(1).Rd.inactive; in2 = Y(2).Rd.inactive;
  assert (all (Y(1).Rd.m(in1) < R39.b(in1)) && all (Y(2).Rd.m(in2) < R44.b(in2)));
  dC = max (abs ([Y(1).Rd.cost_without(in1) - R39.C; Y(2).Rd.cost_without(in2) - R44.C; ...
                  Y(1).Rd.cost_without_all - R39.C; Y(2).Rd.cost_without_all - R44.C]));
  dX = max (Y(1).Rd.x_without_all_dev, Y(2).Rd.x_without_all_dev);
  P (['Для кожного неактивного рядка обчислено ', ...
      '$m_j=\\min\\{A_{j\\cdot}x:\\ A_{k\\cdot}x\\ge b_k\\ (k\\ne j),\\ x\\ge0\\}$ ', ...
      '(табл.~\\ref{tab:glpk-redundancy}). В усіх %d випадках $m_j<b_j$, тому жодне неактивне обмеження ', ...
      'не є надлишковим. '], numel (in1) + numel (in2));
  P (['Вилучення будь-якого одного рядка з $u_j^*=0$ і всіх чотирьох таких рядків одночасно змінює ', ...
      'мінімальну вартість не більше ніж на $%s$ дол./день, а оптимальний вектор --- не більше ніж на ', ...
      '$%s$ дол./день.\n\n'], sci (dC), sci (dX));

  % ---------------------------------------------------------------------------
  P ('\\paragraph{Семиденна задача.}\n');
  P (['Сума семи окремих добових мінімумів дорівнює %s дол., мінімум спільної семиденної задачі --- %s ', ...
      'дол.; різниця дорівнює $%s$ (табл.~\\ref{tab:glpk-multiday-days}). '], tx (Md.sum_days, 12), ...
     tx (Md.C, 12), sci0 (abs (Md.decomp_gap)));
  P (['Добовий мінімум дорівнює %s дол. для вимог $(3;\\ 70)$, %s дол. для $(3{,}3;\\ 73{,}5)$ і %s дол. ', ...
      'для $(3{,}6;\\ 77)$. '], tx (Md.Cday(1), 12), tx (Md.Cday(2), 12), tx (Md.Cday(3), 12));
  k5 = find (cellfun (@(d) numel (d.support), Md.day) == 5);
  k4 = find (cellfun (@(d) numel (d.support), Md.day) == 4);
  if (numel (k5) + numel (k4) == 7 && ! isempty (k4))
    assert (all (cellfun (@(d) isequal (d.Jplus, [1 3 5 9]), Md.day(k4))));
    P (['У дні %s носій складається з п’яти продуктів. У дні %s він складається з чотирьох продуктів ', ...
        '(без яловичої печінки), а рядок вітаміну~B$_2$ неактивний. '], ...
       strjoin (arrayfun (@(v) sprintf ('%d', v), k5, 'UniformOutput', false), ' і '), ...
       strjoin (arrayfun (@(v) sprintf ('%d', v), k4, 'UniformOutput', false), ', '));
  end
  P (['Кожний із семи добових оптимумів єдиний (точна перевірка сертифіката). Тому сукупність добових ', ...
      'оптимумів єдина, а середні надходження в ній визначено однозначно.\n\n']);

  S = Md.iron;
  P (['Середнє надходження заліза за сім днів у цій сукупності дорівнює %s~мг. Порівняння в цілих числах ', ...
      'показує, що воно строго більше за 12 і %s~мг та строго менше за %s~мг. '], tx (Mx.iron.mean, 9), ...
     tx (S.bounds(2), 5), tx (S.bounds(3), 5));
  P (['За твердженням~1 межі 12 і %s~мг зберігають $C^*$, а межа %s~мг збільшує її. GLPK дає ', ...
      '$C^*=%s$ дол. для перших двох меж і $C^*=%s$ дол. для третьої; приріст дорівнює %s дол. ', ...
      '(табл.~\\ref{tab:glpk-multiday-iron}).\n\n'], tx (S.bounds(2), 5), tx (S.bounds(3), 5), ...
     tx (S.cost(1), 9), tx (S.cost(3), 9), tx (S.delta(3), 9));
  S = Md.protein;
  P (['Для білка на множині $D_j=\\{2,3,5,6,7\\}$ середня добова нижня межа дорівнює %s~г, а середнє ', ...
      'надходження --- %s~г. Воно строго більше за %s і %s~г та строго менше за %s~г. '], ...
     tx (Md.mean_rhs_protein, 1), tx (Mx.protein.mean, 9), tx (S.bounds(1), 1), tx (S.bounds(2), 5), ...
     tx (S.bounds(3), 3));
  P (['GLPK дає $C^*=%s$ дол. для перших двох меж і $C^*=%s$ дол. для третьої; приріст дорівнює %s дол. ', ...
      '(табл.~\\ref{tab:glpk-multiday-protein}).\n\n'], tx (S.cost(1), 9), tx (S.cost(3), 9), tx (S.delta(3), 9));
  P (['Допоміжні максимізації середнього надходження виконано за бюджету $0{,}79671475+10^{-7}$ дол. ', ...
      'Найбільше середнє надходження заліза дорівнює %s~мг, білка на множині $D_j$ --- %s~г. ', ...
      'Це результати з допуском до вартості: бюджет перевищує $C^*$ на $%s$ дол. '], ...
     tx (Md.iron.eps_max, 6), tx (Md.protein.eps_max, 6), sci (Md.budget - Md.C));
  P (['На точній оптимальній грані $\\mathbf1^\\top x=C^*$ мінімум і максимум середнього надходження ', ...
      'збігаються: %s~мг для заліза і %s~г для білка.\n\n'], tx (Md.iron.face_max, 6), ...
     tx (Md.protein.face_max, 6));

  % ---------------------------------------------------------------------------
  nrnd = sum (strcmp ({Cm.kind}, 'round') | strcmp ({Cm.kind}, 'less') ...
              | strncmp ({Cm.kind}, 'exact', 5));
  nok = sum ([Cm.ok] & ! strcmp ({Cm.kind}, 'solver'));
  P ('\\paragraph{Порівняння з текстом роботи.}\n');
  P (['У табл.~\\ref{tab:glpk-comparison} значення з тексту зіставлено з результатами GLPK; таблиця ', ...
      'містить %d рядки. Для %d значень, які не залежать від розв’язувача, результат GLPK після округлення ', ...
      'до наведеної в тексті кількості знаків збігається з текстом у %d випадках. '], numel (Cm), nrnd, nok);
  bad = find (! [Cm.ok]);
  if (isempty (bad))
    P ('Числових розбіжностей не виявлено. ');
  else
    P ('Розбіжності: ');
    for k = bad, P ('%s, %s; ', Cm(k).place, Cm(k).what); end
  end
  P (['Значення $1{,}23\\cdot10^{-15}$ і $2{,}02\\cdot10^{-16}$ у підрозд.~2.3 є числовими похибками ', ...
      'іншого розв’язувача; GLPK дає $%s$ і $%s$.\n\n'], sci (Y(1).Uq.max_span), sci (Y(2).Uq.max_span));

  % ---------------------------------------------------------------------------
  P ('\\paragraph{Запропоновані виправлення.}\n\\begin{enumerate}\n');
  P (['\\item Підрозд.~1.1, «Обчислювальна перевірка». Речення про \\texttt{glpsol} версії~4.65, SciPy і ', ...
      'SymPy описує попередній запуск. Для результатів цього додатка середовище таке: GNU Octave %s, ', ...
      'бібліотека GLPK %s; версія~4.65 стосується лише файлу даних \\texttt{stigler.mod}.\n'], ...
     env.octave, env.glpk_version);
  P (['\\item Підрозд.~2.3. Якщо різниці меж координат наводяться для GLPK, значення ', ...
      '$1{,}23\\cdot10^{-15}$ і $2{,}02\\cdot10^{-16}$ слід замінити на $%s$ і $%s$.\n'], ...
     sci (Y(1).Uq.max_span), sci (Y(2).Uq.max_span));
  if (numel (jj) == 1)
    P (['\\item Файл \\texttt{stigler1944.csv}, продукт №~%d, білок. Значення %d не підтверджено однозначно; ', ...
        'за таблицею~A очікується 393. На числа розділу ця клітинка не впливає.\n'], D44.id(ii), D44.A(jj, ii));
  end
  P (['\\item Підрозд.~1.1, зіставлення з підсумком $59{,}88$. Текст порівнює його зі значенням за 365 днів ', ...
      '(%s дол.); це узгоджується зі статтею. Доцільно додати обґрунтування: стаття не називає кількість ', ...
      'днів, але сума $24{,}50$ дол. на с.~311 відповідає 365 дням.\n'], tx (365 * R44.C, 4));
  P ('\\end{enumerate}\n');
  fclose (fid);
end

function s = p10 (v)
  % 1e-9 -> 10^{-9}
  e = round (log10 (v));
  assert (abs (v - 10 ^ e) < 1e-6 * v);
  s = sprintf ('10^{%d}', e);
end

function s = sci (v)
  if (v == 0), s = '0'; return; end
  e = floor (log10 (abs (v)));
  m = v / 10 ^ e;
  if (abs (m) >= 9.995), m = m / 10; e++; end
  s = sprintf ('%s\\cdot10^{%d}', strrep (sprintf ('%.2f', m), '.', '{,}'), e);
end

function s = sci0 (v)
  s = sci (v);
end
