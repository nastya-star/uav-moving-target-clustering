function r = bi_det (M)
  % BI_DET  Точний визначник цілочислової матриці (розклад за першим рядком).
  % Мінори порядку <= 3 обчислюються в double, якщо оцінка 6*max^3 < 2^53
  % гарантує точність; далі використовується довга арифметика.
  n = rows (M);
  assert (n == columns (M) && all (M(:) == round (M(:))));
  mx = max (abs (M(:)));
  if (n == 1)
    r = bi (M);
  elseif (n == 2 && 2 * mx^2 < 2^53)
    r = bi (M(1,1) * M(2,2) - M(1,2) * M(2,1));
  elseif (n == 3 && 6 * mx^3 < 2^53)
    v = M(1,1) * (M(2,2) * M(3,3) - M(2,3) * M(3,2)) ...
      - M(1,2) * (M(2,1) * M(3,3) - M(2,3) * M(3,1)) ...
      + M(1,3) * (M(2,1) * M(3,2) - M(2,2) * M(3,1));
    r = bi (v);
  else
    r = bi (0);
    for k = 1:n
      if (M(1, k) != 0)
        t = bi_mul (bi (M(1, k) * (-1) ^ (k + 1)), bi_det (M(2:end, [1:k-1, k+1:n])));
        r = bi_add (r, t);
      end
    end
  end
end
