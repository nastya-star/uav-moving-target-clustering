function Cm = stg_compare (cfg, Y, Md, Mx, H)
  % STG_COMPARE  Таблиця «місце в роботі --- значення в тексті --- результат
  % GLPK --- різниця --- висновок».
  %
  % Значення з тексту роботи (diet_corrected.tex) записано тут як константи і
  % використано лише для порівняння. Число вважається підтвердженим, якщо
  % результат GLPK після округлення до кількості знаків, наведеної в тексті,
  % збігається з ним: |GLPK - текст| <= 0.5 * 10^(-nd).

  Cm = struct ('place', {}, 'what', {}, 'text', {}, 'nd', {}, 'glpk', {}, 'kind', {}, ...
               'tstr', {}, 'gstr', {});
  R39 = Y(1).R; R44 = Y(2).R; Q39 = Y(1).Q; Q44 = Y(2).Q;
  nu = cfg.nutrient_uk;
  for k = 1:9, nu{k} = strrep (strrep (nu{k}, 'B$_1$', 'B1'), 'B$_2$', 'B2'); end


  % ---------------- підрозділ 1.1 ---------------------------------------------
  p = 'підрозд. 1.1, обчислювальна перевірка';
  Cm = addc (Cm, p, 'C*(1939), дол./день', 0.108662278206757, 15, R39.C);
  Cm = addc (Cm, p, '365,25 C*(1939), дол.', 39.688897115018, 12, 365.25 * R39.C);
  Cm = addc (Cm, p, '365 C*(1939), дол.', 39.661731545466, 12, 365 * R39.C);

  p = 'табл. 2';
  Cm = addc (Cm, p, 'сума вартостей рядків, 1939', 39.93, 2, H.y1939.sum_cost);
  Cm = addc (Cm, p, 'сума вартостей рядків, 1944', 59.88, 2, H.y1944.sum_cost);

  S = R39.support;   % борошно, печінка, капуста, шпинат, квасоля
  nm39 = {'пшеничне борошно','яловича печінка','капуста','шпинат','біла квасоля'};
  p = 'табл. 3';
  t3 = [299.50, 2.58, 110.70, 22.58, 377.81];
  for k = 1:5
    Cm = addc (Cm, p, [nm39{k}, ', фунтів за 365,25 дня'], t3(k), 2, Q39.lb_36525(S(k)));
  end
  Cm = addc (Cm, p, 'річна вартість ЛП, дол.', 39.69, 2, 365.25 * R39.C);
  Cm = addc (Cm, 'підрозд. 1.1, після табл. 3', 'різниця 39,93 - 365,25 C*, дол.', 0.24, 2, ...
       39.93 - 365.25 * R39.C);

  p = 'табл. 4';
  tx4 = [0.029519061676, 0.001892557291, 0.011214435246, 0.005007660467, 0.061028563527];
  tl4 = [299.495480, 2.579315, 110.704661, 22.580839, 377.808184];
  for k = 1:5
    Cm = addc (Cm, p, [nm39{k}, ', x*, дол./день'], tx4(k), 12, R39.x(S(k)));
    Cm = addc (Cm, p, [nm39{k}, ', фунтів за 365,25 дня'], tl4(k), 6, Q39.lb_36525(S(k)));
  end

  p = 'табл. 5';
  tA = [3.0, 147.413535, 0.8, 60.466922, 5.0, 4.120439, 2.7, 27.315981, 75.0];
  tS = [0, 77.413535, 0, 48.466922, 0, 2.320439, 0, 9.315981, 0];
  tU = [0.008765147, 0, 0.031737713, 0, 0.000400233, 0, 0.016358033, 0, 0.000144118];
  for j = 1:9
    Cm = addc (Cm, p, [nu{j}, ': (Ax*)_j'], tA(j), 6, R39.Ax(j));
    Cm = addc (Cm, p, [nu{j}, ': s_j'], tS(j), 6, R39.s(j));
    Cm = addc (Cm, p, [nu{j}, ': u_j*'], tU(j), 9, R39.u(j));
  end

  p = 'підрозд. 1.1, розрахунок 1944 року';
  Cm = addc (Cm, p, 'C*(1944), дол./день', 0.164110826270237, 15, R44.C);
  Cm = addc (Cm, p, '365,25 C*(1944), дол.', 59.941479295204, 12, 365.25 * R44.C);
  Cm = addc (Cm, p, '365 C*(1944), дол.', 59.900451588637, 12, 365 * R44.C);

  S = R44.support;   % борошно, капуста, шпинат, борошно для млинців, свиняча печінка
  nm44 = {'пшеничне борошно','капуста','шпинат','борошно для млинців','свиняча печінка'};
  p = 'табл. 6';
  tx6 = [0.094472740525, 0.014315196735, 0.004249219142, 0.035917299511, 0.015156370357];
  tl6 = [534.151215, 106.706645, 13.379546, 134.413869, 25.277919];
  for k = 1:5
    Cm = addc (Cm, p, [nm44{k}, ', x*, дол./день'], tx6(k), 12, R44.x(S(k)));
    Cm = addc (Cm, p, [nm44{k}, ', фунтів за 365,25 дня'], tl6(k), 6, Q44.lb_36525(S(k)));
  end

  p = 'табл. 7';
  tA = [3.0, 99.303830, 0.8, 29.475597, 5.0, 3.324068, 2.7, 32.250746, 75.0];
  tS = [0, 29.303830, 0, 17.475597, 0, 1.524068, 0, 14.250746, 0];
  tU = [0.028876611, 0, 0.028312380, 0, 0.000724485, 0, 0.013431654, 0, 0.000199243];
  for j = 1:9
    Cm = addc (Cm, p, [nu{j}, ': (Ax*)_j'], tA(j), 6, R44.Ax(j));
    Cm = addc (Cm, p, [nu{j}, ': s_j'], tS(j), 6, R44.s(j));
    Cm = addc (Cm, p, [nu{j}, ': u_j*'], tU(j), 9, R44.u(j));
  end

  p = 'табл. 8';
  jj = [2, 4, 6, 8];
  t39 = [1.505268, 1.898087, 0.039391, 0.000000];
  t44 = [37.730293, 11.008698, 0.826300, 3.812587];
  for k = 1:4
    Cm = addc (Cm, p, [nu{jj(k)}, ': m_j, 1939'], t39(k), 6, Y(1).Rd.m(jj(k)));
    Cm = addc (Cm, p, [nu{jj(k)}, ': m_j, 1944'], t44(k), 6, Y(2).Rd.m(jj(k)));
  end

  % ---------------- підрозділ 1.2 ---------------------------------------------
  p = 'табл. 10';
  t10 = [0.109, 0.113, 0.120, 0.109, 0.113, 0.120, 0.113];
  for t = 1:7
    Cm = addc (Cm, p, sprintf ('день %d: окрема одноденна задача, дол.', t), t10(t), 3, Md.Cday(t));
    Cm = addc (Cm, p, sprintf ('день %d: день у семиденній задачі, дол.', t), t10(t), 3, Md.Cjoint_day(t));
  end
  Cm = addc (Cm, p, 'разом: сума добових мінімумів, дол.', 0.797, 3, Md.sum_days);
  Cm = addc (Cm, p, 'разом: семиденна задача, дол.', 0.797, 3, Md.C);
  p = 'підрозд. 1.2, після табл. 10';
  Cm = addc (Cm, p, 'модуль різниці C* і суми C_t* менший за 10^-12', 1e-12, NaN, abs (Md.decomp_gap), 'less');
  Cm = addc (Cm, p, 'середнє надходження заліза, мг', 62.03914, 5, Md.iron.mean_joint);
  Cm = addc (Cm, p, 'середнє добових меж заліза, мг', 12, 0, Md.mean_rhs_iron);
  Cm = addc (Cm, p, 'найбільше середнє заліза за бюджету 0,79671475+10^-7, мг', 62.03917, 5, Md.iron.eps_max);
  Cm = addc (Cm, p, '1,05 x найбільше середнє заліза, мг', 65.14113, 5, 1.05 * Md.iron.eps_max);
  p = 'табл. 11';
  tc = [0.796715, 0.796715, 0.809187]; td = [0, 0, 0.012472];
  for k = 1:3
    Cm = addc (Cm, p, sprintf ('B = %.5f мг: C*, дол.', cfg.md_iron_bounds(k)), tc(k), 6, Md.iron.cost(k));
    Cm = addc (Cm, p, sprintf ('B = %.5f мг: приріст C*, дол.', cfg.md_iron_bounds(k)), td(k), 6, Md.iron.delta(k));
  end

  % ---------------- підрозділ 1.3 ---------------------------------------------
  p = 'підрозд. 1.3, обчислювальна перевірка';
  Cm = addc (Cm, p, 'вартість семиденної задачі, дол.', 0.79671475, 8, Md.C);
  Cm = addc (Cm, p, 'середня добова межа білка на D_j, г', 74.9, 1, Md.mean_rhs_protein);
  Cm = addc (Cm, p, 'середнє надходження білка на D_j, г', 158.66131, 5, Md.protein.mean_joint);
  Cm = addc (Cm, p, 'найбільше середнє білка за бюджету 0,79671475+10^-7, г', 158.66135, 5, Md.protein.eps_max);
  Cm = addc (Cm, p, '1,05 x найбільше середнє білка, г', 166.594, 3, 1.05 * Md.protein.eps_max);
  p = 'табл. 12';
  tc = [0.796715, 0.796715, 0.815476]; td = [0, 0, 0.018761];
  for k = 1:3
    Cm = addc (Cm, p, sprintf ('межа %.5f г: вартість, дол.', cfg.md_protein_bounds(k)), tc(k), 6, Md.protein.cost(k));
    Cm = addc (Cm, p, sprintf ('межа %.5f г: приріст, дол.', cfg.md_protein_bounds(k)), td(k), 6, Md.protein.delta(k));
  end
  p = 'підрозд. 1.3, після табл. 12';
  Cm = addc (Cm, p, 'вартість за межі 166,594 г, дол.', 0.81547572, 8, Md.protein.cost(3));
  Cm = addc (Cm, p, 'приріст за межі 166,594 г, дол.', 0.01876097, 8, Md.protein.delta(3));

  % ---------------- розділ 2 --------------------------------------------------
  p = 'підрозд. 2.3';
  Cm = addc (Cm, p, 'найбільша різниця меж координат, 1939 (154 задачі)', 1.23e-15, NaN, Y(1).Uq.max_span, 'solver');
  Cm = addc (Cm, p, 'найбільша різниця меж координат, 1944 (28 задач)', 2.02e-16, NaN, Y(2).Uq.max_span, 'solver');
  p = 'підрозд. 2.4';
  % det A_{J+,S} = det(10 A_{J+,S}) / 10^5; рівності перевіряються в цілих числах
  ok39 = bi_sub (bi_mul (bi (625), Y(1).E.det10), ...
                 bi_mul (bi (-100000), bi ('65357009378779'))).s == 0;
  ok44 = bi_sub (bi_mul (bi (5000), Y(2).E.det10), ...
                 bi_mul (bi (100000), bi ('267315835328303'))).s == 0;
  Cm = addc (Cm, p, 'det A(J+,S), 1939', -65357009378779 / 625, NaN, ...
       bi_double (Y(1).E.det10) / 1e5, ifelse_str (ok39, 'exact_ok', 'exact_bad'));
  Cm(end).tstr = '-65357009378779/625'; Cm(end).gstr = [bi_str(Y(1).E.det10), '/100000'];
  Cm = addc (Cm, p, 'det A(J+,S), 1944', 267315835328303 / 5000, NaN, ...
       bi_double (Y(2).E.det10) / 1e5, ifelse_str (ok44, 'exact_ok', 'exact_bad'));
  Cm(end).tstr = '267315835328303/5000'; Cm(end).gstr = [bi_str(Y(2).E.det10), '/100000'];
  Cm = addc (Cm, p, 'найменша зведена вартість поза носієм, 1939', 0.04366642, 8, ...
       min (R39.r(setdiff (1:numel (R39.x), R39.support))));
  Cm = addc (Cm, p, 'найменша зведена вартість поза носієм, 1944', 0.09656077, 8, ...
       min (R44.r(setdiff (1:numel (R44.x), R44.support))));

  % ---------------- підрозділ 3.1 ---------------------------------------------
  p = 'табл. 13';
  t39 = [0.000262954, 0, 0.000253902, 0, 0.000020012, 0, 0.000441667, 0, 0.000108088];
  t44 = [0.000866298, 0, 0.000226499, 0, 0.000036224, 0, 0.000362655, 0, 0.000149432];
  for j = 1:9
    Cm = addc (Cm, p, [nu{j}, ': приріст C*, 1939'], t39(j), 9, Y(1).Sn.delta(j));
    Cm = addc (Cm, p, [nu{j}, ': приріст C*, 1944'], t44(j), 9, Y(2).Sn.delta(j));
  end
  p = 'підрозд. 3.1';
  Cm = addc (Cm, p, 'найбільший модуль різниці приросту і 0,01 b_j u_j менший за 10^-12 (18 випадків)', 1e-12, NaN, ...
       max (abs ([Y(1).Sn.diff; Y(2).Sn.diff])), 'less');
  Cm = addc (Cm, p, 'C* за всіх вимог +1%, 1939, дол./день', 0.109748900989, 12, Y(1).Sn.all_cost);
  Cm = addc (Cm, p, 'C* за всіх вимог +1%, 1944, дол./день', 0.165751934533, 12, Y(2).Sn.all_cost);

  % ---------------- висновки --------------------------------------------------
  for k = 1:numel (Cm)
    c = Cm(k);
    Cm(k).diff = c.glpk - c.text;
    switch (c.kind)
      case 'round'
        tol = 0.5 * 10 ^ (-c.nd);
        Cm(k).ok = abs (Cm(k).diff) <= tol * (1 + 1e-6) + 4 * eps (abs (c.text));
        if (Cm(k).ok)
          Cm(k).verdict = 'підтверджено';
        else
          Cm(k).verdict = sprintf ('розбіжність; пропоноване значення %.*f', c.nd, c.glpk);
        end
      case 'less'
        Cm(k).ok = c.glpk < c.text;
        if (Cm(k).ok)
          Cm(k).verdict = 'підтверджено (нерівність виконується)';
        else
          Cm(k).verdict = sprintf ('нерівність не виконується; фактично %.3g', c.glpk);
        end
      case 'solver'
        Cm(k).ok = c.glpk < 1e-12;
        Cm(k).verdict = sprintf (['числова похибка, залежить від розв’язувача; ', ...
                                  'для GLPK пропоноване значення %.2e'], c.glpk);
      case 'exact_ok'
        Cm(k).ok = true;
        Cm(k).verdict = 'підтверджено точно (цілочислова арифметика)';
      case 'exact_bad'
        Cm(k).ok = false;
        Cm(k).verdict = 'розбіжність із точним значенням';
    end
  end
end

function Cm = addc (Cm, place, what, textv, nd, glpkv, kind)
  if (nargin < 7), kind = 'round'; end
  Cm(end+1) = struct ('place', place, 'what', what, 'text', textv, 'nd', nd, ...
                      'glpk', glpkv, 'kind', kind, 'tstr', '', 'gstr', '');
end

function s = ifelse_str (c, a, b)
  if (c), s = a; else, s = b; end
end
