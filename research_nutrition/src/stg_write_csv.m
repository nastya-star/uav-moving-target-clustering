function stg_write_csv (cfg, env, Y, Dc, Md, Mx, H)
  % STG_WRITE_CSV  Таблиці CSV із повною числовою точністю (%.17g).
  global STG_RUNS
  nk = cfg.nutrient_keys; o = cfg.csvdir;

  % --- середовище і параметри ------------------------------------------------
  rowsc = {'octave_version', env.octave; 'glpk_library_version', env.glpk_version; ...
           'glpk_oct_file', env.glpk_oct; 'glpk_shared_library', env.glpk_lib; ...
           'packages', env.packages; 'glpsol', env.glpsol; 'os', env.os; ...
           'host', env.host; 'run_date', env.date; 'sha256', env.sha256};
  f = fieldnames (cfg.glpk);
  for k = 1:numel (f), rowsc(end+1, :) = {['glpk.', f{k}], cfg.glpk.(f{k})}; end
  for nm = {'tol_feas','tol_gap','tol_comp','tol_support','tol_active','lb_gram', ...
            'md_budget_base','md_budget_eps'}
    rowsc(end+1, :) = {nm{1}, cfg.(nm{1})};
  end
  stg_csv (fullfile (o, 'environment.csv'), {'parameter', 'value'}, rowsc);

  for y = 1:numel (Y)
    D = Y(y).D; R = Y(y).R; E = Y(y).E; Uq = Y(y).Uq; Sn = Y(y).Sn; Rd = Y(y).Rd; Q = Y(y).Q;
    n = columns (D.A); L = D.label;

    % --- матриця даних -------------------------------------------------------
    rowsc = cell (n, 6 + 9 + 2);
    for i = 1:n
      rowsc(i, 1:6) = {i, D.id(i), D.key{i}, D.name{i}, D.unit{i}, D.price(i)};
      for j = 1:9, rowsc{i, 6 + j} = D.A(j, i); end
      rowsc{i, 16} = D.weight(i); rowsc{i, 17} = D.lb_per_unit(i);
    end
    stg_csv (fullfile (o, ['data_', L, '.csv']), ...
             [{'index','table_id','key','name','unit','price_cents'}, nk, ...
              {'edible_grams_per_dollar','lb_per_trade_unit'}], rowsc);

    % --- продукти ------------------------------------------------------------
    xnum = repmat ({'0'}, n, 1);
    for p = 1:numel (R.support), xnum{R.support(p)} = bi_str (E.X{p}); end
    hdr = {'index','table_id','key','name','unit','price_cents','x_dollars_per_day', ...
           'dual_lp_row_multiplier','reduced_cost_1_minus_ATu','reduced_cost_glpk', ...
           'in_support','exact_x_numerator','exact_reduced_cost_sign', ...
           'exact_reduced_cost_value','units_per_day','units_per_365_days', ...
           'units_per_365.25_days','lb_per_trade_unit','lb_per_day','lb_per_365_days', ...
           'lb_per_365.25_days','dollars_per_365_days','dollars_per_365.25_days', ...
           'face_min_x','face_max_x','face_span','min_errnum','min_status', ...
           'max_errnum','max_status'};
    rowsc = cell (n, numel (hdr));
    for i = 1:n
      rowsc(i, :) = {i, D.id(i), D.key{i}, D.name{i}, D.unit{i}, D.price(i), R.x(i), ...
                     R.x_dual(i), R.r(i), R.r_glpk(i), any(R.support == i), xnum{i}, ...
                     E.redcost_sign(i), E.r(i), Q.z_day(i), Q.z_365(i), Q.z_36525(i), ...
                     D.lb_per_unit(i), Q.lb_day(i), Q.lb_365(i), Q.lb_36525(i), ...
                     Q.cost_365(i), Q.cost_36525(i), Uq.lo(i), Uq.hi(i), Uq.span(i), ...
                     Uq.st(i, 1), Uq.st(i, 2), Uq.st(i, 3), Uq.st(i, 4)};
    end
    stg_csv (fullfile (o, ['solution_', L, '_products.csv']), hdr, rowsc);

    % --- нутрієнти -----------------------------------------------------------
    unum = repmat ({'0'}, 9, 1);
    for p = 1:numel (R.Jplus), unum{R.Jplus(p)} = bi_str (E.U{p}); end
    hdr = {'index','nutrient','b','Ax','slack','u','u_from_dual_lp','active', ...
           'exact_u_numerator','exact_slack_sign','exact_slack_value', ...
           'min_intake_without_own_row','cost_without_row','cost_without_row_minus_C', ...
           'cost_b_plus_1pct','delta_cost','predicted_0.01_b_u','delta_minus_predicted', ...
           'basis_kept_exact'};
    rowsc = cell (9, numel (hdr));
    for j = 1:9
      rowsc(j, :) = {j, nk{j}, R.b(j), R.Ax(j), R.s(j), R.u(j), R.u_dual(j), ...
                     any(R.active == j), unum{j}, E.slack_sign(j), E.s(j), Rd.m(j), ...
                     Rd.cost_without(j), Rd.cost_without(j) - R.C, Sn.cost(j), ...
                     Sn.delta(j), Sn.pred(j), Sn.diff(j), Sn.basis_kept(j)};
    end
    stg_csv (fullfile (o, ['solution_', L, '_nutrients.csv']), hdr, rowsc);

    % --- підсумки, перевірки, точний сертифікат ----------------------------------
    c = R.checks;
    rowsc = {'C_dollars_per_day', R.C, ''; 'C_dual_lp', R.C_dual, ''; ...
             'C_times_365', 365 * R.C, ''; 'C_times_365.25', 365.25 * R.C, ''; ...
             'primal_errnum', R.errnum(1), '0'; 'primal_status', R.status(1), '5'; ...
             'dual_errnum', R.errnum(2), '0'; 'dual_status', R.status(2), '5'; ...
             'primal_infeasibility', c.primal_infeas, sprintf('%g', cfg.tol_feas); ...
             'dual_infeasibility', c.dual_infeas, sprintf('%g', cfg.tol_feas); ...
             'duality_gap_abs', c.gap, sprintf('%g', cfg.tol_gap); ...
             'primal_lp_minus_dual_lp_abs', c.gap_two_lps, sprintf('%g', cfg.tol_gap); ...
             'max_abs_u_times_slack', c.comp_rows, sprintf('%g', cfg.tol_comp); ...
             'max_abs_x_times_reduced_cost', c.comp_cols, sprintf('%g', cfg.tol_comp); ...
             'max_abs_u_minus_dual_lp_u', c.u_vs_dual_lp, sprintf('%g', cfg.tol_feas); ...
             'max_abs_x_minus_dual_lp_multipliers', c.x_vs_dual_lp, sprintf('%g', cfg.tol_feas); ...
             'max_abs_r_minus_glpk_redcosts', c.r_vs_glpk, ''; ...
             'all_checks_passed', R.ok, '1'; ...
             'support_indices', sprintf('%d ', R.support), ''; ...
             'active_rows', sprintf('%d ', R.active), ''; ...
             'rows_with_positive_u', sprintf('%d ', R.Jplus), ''; ...
             'uniqueness_lp_count', Uq.n_lp, ''; ...
             'uniqueness_all_errnum0_status5', Uq.all_optimal, '1'; ...
             'uniqueness_max_abs_span', Uq.max_span, ''; ...
             'uniqueness_max_abs_dev_from_x', Uq.max_dev_from_x, ''; ...
             'exact_det_of_10A_JS', bi_str(E.det10), ''; ...
             'exact_det_A_JS_as_fraction', [bi_str(E.det10), '/100000'], ''; ...
             'exact_det_A_JS_decimal', bi_double(E.det10) / 1e5, ''; ...
             'exact_common_denominator_abs_det10', bi_str(E.Dpos), ''; ...
             'exact_C_numerator_over_denominator', [bi_str(E.sumX), '/', bi_str(E.Dpos)], ''; ...
             'exact_C_decimal', E.C, ''; ...
             'exact_x_positive_on_support', E.x_pos, '1'; ...
             'exact_u_positive_on_Jplus', E.u_pos, '1'; ...
             'exact_Ax_ge_b', E.rows_feasible, '1'; ...
             'exact_slack_positive_off_Jplus', E.rows_strict, '1'; ...
             'exact_ATu_le_1', E.cols_feasible, '1'; ...
             'exact_reduced_cost_positive_off_support', E.cols_strict, '1'; ...
             'exact_zero_duality_gap', E.gap_zero, '1'; ...
             'exact_primal_optimum_unique', E.unique, '1'; ...
             'exact_dual_optimum_unique', E.dual_unique, '1'; ...
             'min_reduced_cost_off_support', min(E.r(setdiff(1:n, R.support))), ''; ...
             'max_abs_x_glpk_minus_exact', max(abs(R.x(R.support) - E.x)), ''; ...
             'max_abs_u_glpk_minus_exact', max(abs(R.u(R.Jplus) - E.u)), ''; ...
             'abs_C_glpk_minus_exact', abs(R.C - E.C), ''; ...
             'cost_all_requirements_plus_1pct', Sn.all_cost, ''; ...
             'delta_all_plus_1pct', Sn.all_delta, ''; ...
             'predicted_0.01_C', Sn.all_pred, ''; ...
             'sum_of_nine_single_deltas', Sn.all_sum_single, ''; ...
             'all_plus_1pct_basis_kept_exact', Sn.all_basis_kept, '1'; ...
             'max_abs_delta_minus_predicted', max(abs(Sn.diff)), ''; ...
             'cost_without_all_zero_u_rows', Rd.cost_without_all, ''; ...
             'cost_without_all_zero_u_rows_minus_C', Rd.cost_without_all - R.C, ''; ...
             'max_abs_x_change_without_zero_u_rows', Rd.x_without_all_dev, ''};
    stg_csv (fullfile (o, ['summary_', L, '.csv']), {'quantity', 'value', 'required_or_tolerance'}, rowsc);
  end

  % --- перевірка даних ---------------------------------------------------------
  D39 = Y(1).D; D44 = Y(2).D;
  rowsc = {};
  for i = 1:columns (D39.A)
    rowsc(end+1, :) = {i, D39.key{i}, D39.unit{i}, D39.price(i), D39.weight(i), ...
                       D39.lb_per_unit(i) * cfg.lb_gram, Dc.edible(i), Dc.edible_cap(i), ...
                       (isnan(Dc.edible(i)) || Dc.edible(i) <= Dc.edible_cap(i))};
  end
  stg_csv (fullfile (o, 'datacheck_1939_weight_per_dollar.csv'), ...
           {'index','key','unit','price_cents','edible_grams_per_dollar','grams_per_trade_unit', ...
            'edible_fraction','max_fraction_allowed_by_rounding','consistent'}, rowsc);
  rowsc = {};
  for i = 1:columns (D44.A)
    for j = 1:9
      rowsc(end+1, :) = {D44.id(i), D44.name{i}, Dc.name39{i}, nk{j}, D44.price(i), ...
                         Dc.ratio(i), D44.A(j, i), Dc.pred(j, i), Dc.dev_units(j, i)};
    end
  end
  stg_csv (fullfile (o, 'datacheck_1944_vs_1939.csv'), ...
           {'table_id','name_1944','name_1939','nutrient','price_1944_cents', ...
            'price_ratio_1939_over_1944','value_table_B','value_1939_times_ratio', ...
            'deviation_in_print_units'}, rowsc);

  % --- багатоденні експерименти ------------------------------------------------
  rowsc = {};
  for t = 1:7
    rowsc(end+1, :) = {t, Md.bt(1, t), Md.bt(2, t), Md.Cday(t), Md.Cjoint_day(t), ...
                       Md.Cjoint_day(t) - Md.Cday(t), Md.day{t}.errnum(1), Md.day{t}.status(1), ...
                       sprintf('%d ', Md.day{t}.support), sprintf('%d ', Md.day{t}.Jplus), ...
                       Mx.day_unique(t)};
  end
  rowsc(end+1, :) = {'sum', NaN, NaN, Md.sum_days, Md.C, Md.decomp_gap, NaN, NaN, '', '', ...
                     Mx.all_days_unique};
  stg_csv (fullfile (o, 'multiday_days.csv'), ...
           {'day','energy_bound','protein_bound','single_day_min_cost','day_cost_in_joint_lp', ...
            'difference','errnum','status','support','rows_with_positive_u', ...
            'exact_unique_daily_optimum'}, rowsc);
  rowsc = {};
  for t = 1:7
    for i = 1:columns (D39.A)
      rowsc(end+1, :) = {t, i, D39.key{i}, Md.day{t}.x(i), Md.Xjoint(i, t)};
    end
  end
  stg_csv (fullfile (o, 'multiday_x.csv'), {'day','index','key','x_single_day_lp','x_joint_lp'}, rowsc);
  rowsc = {};
  for nm = {'iron', 'protein'}
    S = Md.(nm{1}); X = [];
    if (isfield (Mx, nm{1})), X = Mx.(nm{1}); end
    rowsc(end+1, :) = {nm{1}, 'mean_in_joint_solution', NaN, S.mean_joint, NaN, NaN, NaN, ''};
    rowsc(end+1, :) = {nm{1}, 'mean_in_daily_optima', NaN, S.mean_days, NaN, NaN, NaN, ''};
    rowsc(end+1, :) = {nm{1}, 'min_mean_on_exact_optimal_face', NaN, S.face_min, Md.C, NaN, NaN, ''};
    rowsc(end+1, :) = {nm{1}, 'max_mean_on_exact_optimal_face', NaN, S.face_max, Md.C, NaN, NaN, ''};
    rowsc(end+1, :) = {nm{1}, 'max_mean_with_cost_tolerance', NaN, S.eps_max, S.eps_cost, ...
                       S.eps_cost - Md.C, S.eps_budget_dual, ...
                       sprintf('budget %.17g', S.eps_budget)};
    if (! isempty (X))
      rowsc(end+1, :) = {nm{1}, 'exact_mean_in_unique_daily_optima', NaN, X.mean, NaN, NaN, NaN, ...
                         'rational value, printed as double'};
    end
    for k = 1:numel (S.bounds)
      note = '';
      if (! isempty (X)), note = sprintf ('exact sign(mean - bound) = %d', X.cmp(k)); end
      rowsc(end+1, :) = {nm{1}, sprintf('lower_bound_case_%d', k), S.bounds(k), S.mean_at_opt(k), ...
                         S.cost(k), S.delta(k), S.mult(k), note};
    end
  end
  stg_csv (fullfile (o, 'multiday_average.csv'), ...
           {'nutrient','quantity','average_lower_bound','average_intake','cost', ...
            'cost_minus_base_cost','multiplier','note'}, rowsc);

  % --- історичні раціони ---------------------------------------------------------
  rowsc = {};
  yy = {'y1939', 'y1944'};
  for y = 1:2
    h = H.(yy{y}); D = Y(y).D; R = Y(y).R; Q = Y(y).Q;
    for k = 1:numel (h.idx)
      i = h.idx(k);
      rowsc(end+1, :) = {D.label, 'product', D.name{i}, h.qty(k), h.qty_unit{k}, h.units(k), ...
                         h.cost(k), h.cost_from_qty(k), Q.z_365(i), Q.z_36525(i), ...
                         Q.cost_365(i), Q.cost_36525(i)};
    end
    rowsc(end+1, :) = {D.label, 'total', '', NaN, '', NaN, h.sum_cost, h.sum_cost_from_qty, ...
                       NaN, NaN, 365 * R.C, 365.25 * R.C};
  end
  stg_csv (fullfile (o, 'historic_products.csv'), ...
           {'year','row','product','stigler_quantity','quantity_unit','stigler_trade_units', ...
            'stigler_cost','cost_from_quantity_and_price','lp_trade_units_365_days', ...
            'lp_trade_units_365.25_days','lp_cost_365_days','lp_cost_365.25_days'}, rowsc);
  rowsc = {};
  for y = 1:2
    h = H.(yy{y}); D = Y(y).D; R = Y(y).R;
    for j = 1:9
      rowsc(end+1, :) = {D.label, nk{j}, R.b(j), h.intake_cost(j, 1), h.ratio_cost(j, 1), ...
                         h.intake_cost(j, 2), h.ratio_cost(j, 2), h.intake_qty(j, 1), ...
                         h.ratio_qty(j, 1), h.intake_qty(j, 2), h.ratio_qty(j, 2)};
    end
    rowsc(end+1, :) = {D.label, 'budget_over_lp_minimum', NaN, h.daily_budget(1), h.theta(1), ...
                       h.daily_budget(2), h.theta(2), NaN, NaN, NaN, NaN};
    rowsc(end+1, :) = {D.label, 'lp_minimum_365_coefficients_plus_half_print_step', NaN, ...
                       365 * h.C_up, NaN, NaN, NaN, NaN, NaN, NaN, NaN};
    rowsc(end+1, :) = {D.label, 'lp_minimum_365_coefficients_minus_half_print_step', NaN, ...
                       365 * h.C_dn, NaN, NaN, NaN, NaN, NaN, NaN, NaN};
    for j = 1:9
      rowsc(end+1, :) = {D.label, ['ratio_365_coefficients_plus_half_step_', nk{j}], R.b(j), ...
                         h.ratio_cost_up(j) * R.b(j), h.ratio_cost_up(j), NaN, NaN, NaN, NaN, NaN, NaN};
    end
  end
  stg_csv (fullfile (o, 'historic_nutrients.csv'), ...
           {'year','nutrient','b','intake_costs_365','ratio_costs_365','intake_costs_365.25', ...
            'ratio_costs_365.25','intake_quantities_365','ratio_quantities_365', ...
            'intake_quantities_365.25','ratio_quantities_365.25'}, rowsc);

  % --- журнал усіх запусків GLPK -------------------------------------------------
  rowsc = cell (numel (STG_RUNS), 8);
  for k = 1:numel (STG_RUNS)
    r = STG_RUNS(k);
    rowsc(k, :) = {k, r.tag, r.rows, r.cols, r.sense, r.errnum, r.status, r.fval};
  end
  stg_csv (fullfile (o, 'lp_runs.csv'), ...
           {'run','tag','rows','columns','sense','errnum','status','objective'}, rowsc);
end
