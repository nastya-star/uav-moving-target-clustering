function s = stg_name_uk (D, i)
  % STG_NAME_UK  Українська назва продукту (для таблиць); інакше назва з файлу.
  map = {'Wheat Flour (Enriched)', 'Пшеничне борошно'; 'Wheat flour', 'Пшеничне борошно'; ...
         'Liver (Beef)', 'Яловича печінка'; 'Cabbage', 'Капуста'; 'Spinach', 'Шпинат'; ...
         'Navy Beans, Dried', 'Сушена біла квасоля'; 'Navy beans', 'Сушена біла квасоля'; ...
         'Pancake flour', 'Борошно для млинців'; 'Pork liver', 'Свиняча печінка'; ...
         'Evaporated Milk (can)', 'Згущене молоко'; 'Evaporated milk', 'Згущене молоко'};
  k = find (strcmp (map(:, 1), D.name{i}), 1);
  if (isempty (k)), s = D.name{i}; else, s = map{k, 2}; end
end
